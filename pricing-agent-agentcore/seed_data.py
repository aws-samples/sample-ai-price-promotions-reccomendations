# ═══════════════════════════════════════════════════════════════════════════
# Nova Lite: Text generation via Converse API
# ═══════════════════════════════════════════════════════════════════════════

def invoke_nova_lite(prompt: str, max_tokens: int = 4096, temperature: float = 0.7) -> str:
    """Generate text using Amazon Nova Lite via the Converse API."""
    logger.info("Invoking Nova Lite (prompt length: %d chars)", len(prompt))

    response = bedrock_runtime.converse(
        modelId=NOVA_LITE_MODEL_ID,
        messages=[
            {
                "role": "user",
                "content": [{"text": prompt}],
            }
        ],
        inferenceConfig={
            "maxTokens": max_tokens,
            "temperature": temperature,
        },
    )

    output_text = response["output"]["message"]["content"][0]["text"]
    logger.info("Nova Lite response: %d chars", len(output_text))
    return output_text


def invoke_nova_lite_json(prompt: str, max_tokens: int = 4096) -> dict | list:
    """Generate structured JSON using Nova Lite. Retries once on parse failure."""
    full_prompt = (
        f"{prompt}\n\n"
        "IMPORTANT: Respond with ONLY valid JSON. No markdown, no code fences, "
        "no explanation text before or after the JSON."
    )

    for attempt in range(2):
        raw = invoke_nova_lite(full_prompt, max_tokens=max_tokens, temperature=0.5)

        # Strip markdown code fences if present
        cleaned = raw.strip()
        if cleaned.startswith("```"):
            lines = cleaned.split("\n")
            # Remove first line (```json) and last line (```)
            lines = [l for l in lines if not l.strip().startswith("```")]
            cleaned = "\n".join(lines)

        try:
            return json.loads(cleaned)
        except json.JSONDecodeError as exc:
            logger.warning("JSON parse failed (attempt %d): %s", attempt + 1, exc)
            if attempt == 0:
                logger.info("Retrying with stricter prompt...")
                continue
            raise ValueError(f"Failed to parse Nova Lite JSON output: {exc}\nRaw: {raw[:500]}")



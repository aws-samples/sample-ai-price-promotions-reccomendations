# Nova Canvas: Image generation via InvokeModel API
# ═══════════════════════════════════════════════════════════════════════════

def generate_product_image(product_name: str, product_description: str, output_path: str):
    """Generate a product image using Amazon Nova Canvas text-to-image."""
    prompt = (
        f"Professional product photography of {product_name}. "
        f"{product_description}. "
        "Clean white background, studio lighting, high resolution, "
        "commercial product shot, centered composition, no text or watermarks."
    )
    return _generate_image_to_file(prompt[:1024], output_path)


def _generate_image_to_file(prompt: str, output_path: str, width: int = 1024, height: int = 1024) -> bool:
    """Generate an image with Nova Canvas and save to a local file."""
    body = json.dumps({
        "taskType": "TEXT_IMAGE",
        "textToImageParams": {"text": prompt[:1024]},
        "imageGenerationConfig": {
            "numberOfImages": 1,
            "quality": "standard",
            "height": height,
            "width": width,
            "cfgScale": 7.0,
            "seed": random.randint(0, 2147483646),  # nosec B311 - Used for image generation variation, not security
        },
    })

    logger.info("Generating image: %s", os.path.basename(output_path))

    try:
        response = bedrock_runtime_images.invoke_model(
            body=body,
            modelId=NOVA_CANVAS_MODEL_ID,
            accept="application/json",
            contentType="application/json",
        )
        response_body = json.loads(response["body"].read())

        if "error" in response_body:
            logger.error("Nova Canvas error: %s", response_body["error"])
            return False

        images = response_body.get("images", [])
        if not images:
            logger.error("No images returned")
            return False

        image_bytes = base64.b64decode(images[0])
        os.makedirs(os.path.dirname(output_path), exist_ok=True)
        with open(output_path, "wb") as f:
            f.write(image_bytes)

        logger.info("Saved: %s (%d bytes)", output_path, len(image_bytes))
        return True

    except ClientError as exc:
        logger.error("Nova Canvas API error: %s", exc)
        return False


